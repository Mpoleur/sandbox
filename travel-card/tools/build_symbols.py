# Converts assets/symbols/*.svg into app/src/generated/symbols.generated.ts (shape data drawn by react-native-svg).
# The artwork files are only read. A hash of the folder is stored so a test can detect drawings that changed.
# The lossless check (generated data against an independent parse of each SVG) is in app/tests/symbols.fidelity.test.ts.
import hashlib, math, os, re, sys
from lxml import etree

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'symbols')
OUT = os.path.join(ROOT, 'app', 'src', 'generated', 'symbols.generated.ts')
ALLOWED = {'path', 'rect', 'circle', 'ellipse', 'g'}
CAMEL = {'stroke-width': 'strokeWidth', 'stroke-linecap': 'strokeLinecap', 'stroke-linejoin': 'strokeLinejoin',
         'stroke-dasharray': 'strokeDasharray'}


def nums(s):
    return [float(x) for x in re.findall(r'-?\d*\.?\d+(?:e-?\d+)?', s)]


def mul(a, b):  # 2x3 affine matrices as (a,b,c,d,e,f); result = a * b
    return (a[0] * b[0] + a[2] * b[1], a[1] * b[0] + a[3] * b[1],
            a[0] * b[2] + a[2] * b[3], a[1] * b[2] + a[3] * b[3],
            a[0] * b[4] + a[2] * b[5] + a[4], a[1] * b[4] + a[3] * b[5] + a[5])


def matrix_of(t):
    m = (1, 0, 0, 1, 0, 0)
    for fn, args in re.findall(r'([a-zA-Z]+)\(([^)]*)\)', t):
        v = nums(args)
        if fn == 'translate':
            n = (1, 0, 0, 1, v[0], v[1] if len(v) > 1 else 0)
        elif fn == 'scale':
            n = (v[0], 0, 0, v[1] if len(v) > 1 else v[0], 0, 0)
        elif fn == 'rotate':
            a = math.radians(v[0]); c, s = math.cos(a), math.sin(a)
            n = (c, s, -s, c, 0, 0)
            if len(v) == 3:
                n = mul(mul((1, 0, 0, 1, v[1], v[2]), n), (1, 0, 0, 1, -v[1], -v[2]))
        elif fn == 'matrix':
            n = tuple(v)
        else:
            sys.exit(f'unsupported transform {fn}')
        m = mul(m, n)
    return [round(x, 6) + 0.0 for x in m]


def conv(el):
    tag = etree.QName(el).localname
    if tag not in ALLOWED:
        sys.exit(f'unexpected element {tag}')
    props = {}
    for k, v in el.attrib.items():
        if k == 'transform':
            props['transform'] = matrix_of(v)
        elif k == 'stroke-dasharray':
            props['strokeDasharray'] = nums(v)
        else:
            props[CAMEL.get(k, k)] = v
    kids = [conv(c) for c in el if isinstance(c.tag, str)]
    return [tag, props, kids]


def folder_hash():
    h = hashlib.sha256()
    for f in sorted(os.listdir(SRC)):
        if f.endswith('.svg'):
            h.update(f.encode()); h.update(open(os.path.join(SRC, f), 'rb').read())
    return h.hexdigest()


def main():
    files = sorted(f for f in os.listdir(SRC) if f.endswith('.svg'))
    lines = []
    for f in files:
        root = etree.fromstring(open(os.path.join(SRC, f), 'rb').read())
        if root.get('viewBox') != '0 0 64 64' or root.get('stroke-linejoin') != 'round' or root.get('stroke-linecap') != 'round':
            sys.exit(f'{f}: unexpected root attributes')
        shapes = [conv(c) for c in root if isinstance(c.tag, str)]
        import json
        lines.append(f'  "{f[:-4]}": {json.dumps(shapes, separators=(",", ":"))},')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as o:
        o.write('// GENERATED by tools/build_symbols.py from assets/symbols/*.svg. Do not edit by hand.\n')
        o.write('// Each symbol is a list of shapes [tag, props, children]. transform is a 6-number matrix.\n')
        o.write('export type Shape = [string, Record<string, string | number[]>, Shape[]];\n')
        o.write(f"export const SVG_FOLDER_HASH = '{folder_hash()}';\n")
        o.write('export const SYMBOL_SHAPES: Record<string, Shape[]> = {\n' + '\n'.join(lines) + '\n};\n')
    print(f'{len(files)} symbols written to {os.path.relpath(OUT, ROOT)} ({os.path.getsize(OUT)} bytes)')


if __name__ == '__main__':
    main()
