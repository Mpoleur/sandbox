# Converts the passport-stamp layer of Dali's approved background 4e (docs/design/mockups/home-backgrounds-4.html, read only)
# into app/src/generated/stamps.generated.ts. Only the stamps below y = CROP_Y are kept: they are the bottom-right layer
# that stays fixed while the list scrolls. Flat vector only: paths, circles, ellipses, rectangles, polygons, dashes.
import json, os, re, sys
from lxml import etree

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from build_symbols import matrix_of, nums  # noqa: E402

SRC = os.path.join(ROOT, 'docs', 'design', 'mockups', 'home-backgrounds-4.html')
OUT = os.path.join(ROOT, 'app', 'src', 'generated', 'stamps.generated.ts')
ALLOWED = {'g', 'path', 'circle', 'ellipse', 'rect', 'polygon'}
CAMEL = {'stroke-width': 'strokeWidth', 'stroke-linecap': 'strokeLinecap', 'stroke-linejoin': 'strokeLinejoin',
         'stroke-dasharray': 'strokeDasharray', 'fill-rule': 'fillRule'}
CROP_Y, CROP_H = 520, 240   # the visible part: y 520 to 760 of the 360 x 760 mock-up screen


def conv(el):
    tag = etree.QName(el).localname
    if tag not in ALLOWED:
        sys.exit('unexpected element ' + tag)
    props = {}
    for k, v in el.attrib.items():
        if k == 'transform':
            props['transform'] = matrix_of(v)
        elif k == 'stroke-dasharray':
            props['strokeDasharray'] = nums(v)
        else:
            props[CAMEL.get(k, k)] = v
    return [tag, props, [conv(c) for c in el if isinstance(c.tag, str)]]


def main():
    html = open(SRC, encoding='utf-8').read()
    i = html.index('<h2>4e.')
    m = re.search(r'<div class=scr[^>]*>(<svg class=bgsvg.*?</svg>)', html[i:], flags=re.S)
    svg = m.group(1).replace('class=bgsvg', '').replace('width=360 height=760', 'width="360" height="760"')
    svg = re.sub(r'<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ', svg, count=1)
    root = etree.fromstring(svg.encode('utf-8'))
    kids = [c for c in root if isinstance(c.tag, str)]
    # the first element is the full-screen ground rectangle: the app draws the ground itself
    assert etree.QName(kids[0]).localname == 'rect' and kids[0].get('fill') == '#F3F6FB'
    shapes = [conv(c) for c in kids[1:]]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as o:
        o.write('// GENERATED by tools/build_stamps.py from docs/design/mockups/home-backgrounds-4.html (4e). Do not edit by hand.\n')
        o.write("import type { Shape } from './symbols.generated';\n")
        o.write(f'export const STAMPS_VIEWBOX = "0 {CROP_Y} 360 {CROP_H}";\n')
        o.write(f'export const STAMPS_SIZE = {{ width: 360, height: {CROP_H} }};\n')
        o.write('export const STAMPS: Shape[] = ' + json.dumps(shapes, separators=(',', ':')) + ';\n')
    print(f'{len(shapes)} stamps written to {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
